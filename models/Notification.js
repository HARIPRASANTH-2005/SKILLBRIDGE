
// ─────────────────────────────────────────────
// models/Notification.js
// SkillBridge Notification Management Schema
// ─────────────────────────────────────────────

const mongoose = require('mongoose');

const notificationSchema = new mongoose.Schema(
  {
    // User who receives the notification.
    recipientId: {
      type: mongoose.Schema.Types.ObjectId,
      ref: 'User',
      required: true
    },

    // User who triggered the notification.
    // Null is allowed for system-generated notifications.
    senderId: {
      type: mongoose.Schema.Types.ObjectId,
      ref: 'User',
      default: null
    },

    // Notification category.
    type: {
      type: String,
      enum: [
        'proposal_received',
        'proposal_accepted',
        'proposal_declined',
        'member_added',
        'task_assigned',
        'task_updated',
        'task_completed',
        'submission_received',
        'submission_approved',
        'changes_requested',
        'milestone_updated',
        'project_completed',
        'new_message',
        'system'
      ],
      required: true
    },

    // Notification heading.
    title: {
      type: String,
      required: true,
      trim: true,
      minlength: 2,
      maxlength: 150
    },

    // Notification description.
    message: {
      type: String,
      required: true,
      trim: true,
      minlength: 1,
      maxlength: 1000
    },

    // Optional link to the relevant page.
    link: {
      type: String,
      trim: true,
      maxlength: 500,
      default: ''
    },

    // Optional references to related records.
    relatedProjectId: {
      type: mongoose.Schema.Types.ObjectId,
      ref: 'Project',
      default: null
    },

    relatedTaskId: {
      type: mongoose.Schema.Types.ObjectId,
      ref: 'Task',
      default: null
    },

    relatedProposalId: {
      type: mongoose.Schema.Types.ObjectId,
      ref: 'Proposal',
      default: null
    },

    relatedSubmissionId: {
      type: mongoose.Schema.Types.ObjectId,
      ref: 'Submission',
      default: null
    },

    // Read status.
    readAt: {
      type: Date,
      default: null
    }
  },
  {
    timestamps: true,
    versionKey: '__v'
  }
);


// ─────────────────────────────────────────────
// DATABASE INDEXES
// ─────────────────────────────────────────────

// User notification list, newest first.
notificationSchema.index(
  { recipientId: 1, createdAt: -1 },
  {
    name: 'notification_recipient_date'
  }
);

// Unread notifications for a user.
notificationSchema.index(
  { recipientId: 1, readAt: 1, createdAt: -1 },
  {
    name: 'notification_recipient_read_date'
  }
);

// Find notifications generated by a user.
notificationSchema.index(
  { senderId: 1, createdAt: -1 },
  {
    name: 'notification_sender_date'
  }
);


// ─────────────────────────────────────────────
// MODEL EXPORT
// ─────────────────────────────────────────────

module.exports = mongoose.model(
  'Notification',
  notificationSchema
);
